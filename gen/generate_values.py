#!/usr/bin/env python3
"""Generate goose-qt's values.goose from qtc's inline-value manifest (manifest/qtc_inline.json).

Qt's small value types become Goose structs of the same layout, held by the program with no
handle in qtc's registry:

    let c = qt::color(255, 0, 0);          // qt::Color, made by QColor(int, int, int)
    let r = c.red();
    var g = qt::rect(0, 0, 640, 480);      // qt::Rect
    g.moveTo(10, 10);                      // methods that change it take it by reference
    widget.setGeometry(g);                 // object methods take it too (qtcmi_* entry points)

Struct names drop the Q (Point, PointF, Size, SizeF, Rect, RectF, Line, LineF, Margins,
MarginsF, Color); constructors are the lowercase name (qt::point, qt::rectf); static methods
are lowercase name, underscore, method (qt::color_fromHsv). to_val() and qt::to_color(v) etc.
convert to and from qt::Val. Called by generate_goose.py.
"""
import collections
import json
import os

CTYPE_G = {"int32_t": "i32", "uint16_t": "u16", "double": "f64"}
SCALAR_G = {"int": "i64", "uint": "i64", "double": "f64", "float": "f64", "bool": "bool"}
RET_G = {"int": "i64", "unsigned int": "i64", "uint": "i64", "QRgb": "i64", "bool": "bool", "double": "f64",
         "qreal": "f64", "float": "f64", "void": None}
# among C overloads that map to the same Goose parameters, the first of these wins
PREFER = {"int": 0, "double": 0, "uint": 1, "float": 1, "bool": 2}


def generate(inline_manifest, entries, api_manifest, out_dir, gname_of):
    """gname_of(method name, receiver, goose params) -> the Goose function name api.goose uses
    for that method (keywords and hand-written functions get a trailing _)."""
    man = json.load(open(inline_manifest))
    types = man["types"]
    gtype = {t: d["goose"] for t, d in types.items()}
    externs = {}
    out = ["// Generated by gen/generate_values.py from qtc's qtc_inline.json. Do not edit.",
           "// Qt's small value types as Goose structs with the layout of the Qt type: no handle, no",
           "// registry. qt::rect(0, 0, 640, 480), c.red(), g.moveTo(10, 10), widget.setGeometry(g).",
           "namespace qt;", ""]
    for t, d in types.items():
        out.append("struct %s { %s }" % (d["goose"], ", ".join("%s: %s" % (n, CTYPE_G[ct]) for ct, n in d["fields"])))
    out.append("")

    def gp(p):
        ty, conv = p
        return gtype[ty] if conv == "value" else SCALAR_G[conv]

    def gret(rt):
        return gtype[rt] if rt in gtype else RET_G[rt]

    # one Goose function per (name, self, goose params); prefer int/double overloads
    chosen = collections.OrderedDict()
    for f in man["functions"]:
        t = f["type"]
        g = gtype[t]
        gparams = tuple(gp(p) for p in f["params"])
        if f["kind"] == "ctor":
            name, selfp = g.lower(), None
        elif f["kind"] == "static":
            name, selfp = "%s_%s" % (g.lower(), f["name"]), None
        else:
            name, selfp = f["name"], (g + "&" if f["kind"] == "mut" else g)
        key = (name, selfp.rstrip("&") if selfp else None, gparams)
        rank = sum(PREFER.get(p[1], 0) for p in f["params"])
        if key in chosen and chosen[key][0] <= rank:
            continue
        chosen[key] = (rank, f, name, selfp, gparams)
    nfun = 0
    for key, (rank, f, name, selfp, gparams) in chosen.items():
        rt = gret(f["ret"])
        cparams = (["self_: %s" % selfp] if selfp else []) + ["a%d: %s" % (i, t) for i, t in enumerate(gparams)]
        externs[f["c"]] = "    fn %s(%s)%s;" % (f["c"], ", ".join(cparams), (" -> " + rt) if rt else "")
        args = (["self_"] if selfp else []) + ["a%d" % i for i in range(len(gparams))]
        head = "fn %s(%s)%s" % (name, ", ".join(cparams), (" -> " + rt) if rt else "")
        call = "%s(%s)" % (f["c"], ", ".join(args))
        out.append("%s { %s; }" % (head, ("return " + call) if rt else call))
        nfun += 1
    out.append("")
    # to and from qt::Val, and as arguments of qt::call
    for t, d in types.items():
        g = d["goose"]
        externs["qtc_val_from_" + t] = "    fn qtc_val_from_%s(v: %s) -> u64;" % (t, g)
        externs["qtc_val_to_" + t] = "    fn qtc_val_to_%s(v: u64, out: %s&) -> i32;" % (t, g)
        externs["qtc_ret_" + t] = "    fn qtc_ret_%s() -> %s;" % (t, g)
        externs["qtc_arg_" + t] = "    fn qtc_arg_%s(v: %s);" % (t, g)
        out.append("fn to_val(v: %s) -> Val { return Val { h: qtc_val_from_%s(v) }; }" % (g, t))
        out.append("fn to_%s(v: Val) -> %s { var r = default<%s>(); qtc_val_to_%s(v.h, r); return r; }"
                   % (g.lower(), g, g, t))
        out.append("fn arg(v: %s) { qtc_arg_%s(v); }" % (g, t))
        out.append("fn ret_%s() -> %s { return qtc_ret_%s(); }" % (g.lower(), g, t))
        nfun += 4
    out.append("")
    # object methods that take them: the qtcmi_ entry points
    classes = {c["name"]: c for c in api_manifest["classes"]}
    by_sig = collections.defaultdict(set)   # sig -> receivers (Obj / Val)
    names = {}
    for c in api_manifest["classes"]:
        recv = "Obj" if c["kind"] == "object" else "Val"
        for m in c["methods"]:
            if m["static"]:
                continue
            ps = m["params"]
            for k in range(m["min"], len(ps) + 1):
                sig = "%s(%s)" % (m["name"], ",".join(p["type"] for p in ps[:k]))
                if sig in entries.get("inline_methods", {}):
                    by_sig[sig].add(recv)
                    names[sig] = (m["name"], ps[:k], m["ret"])
    GT = {"bool": "bool", "int": "i64", "uint": "i64", "double": "f64", "str": "const u8[:]", "bytes": "const u8[:]",
          "obj": "Obj", "variant": "Val", "value": "Val", "list": "Val", "map": "Val"}
    groups = collections.OrderedDict()
    for sig in sorted(by_sig):
        mname, ps, ret = names[sig]
        gparams, cparams, ok = [], [], True
        for p in ps:
            if p["pk"] in ("null", "out"):
                continue
            if p["pk"] == "value" and p["type"] in gtype:
                gparams.append(gtype[p["type"]])
                cparams.append(gtype[p["type"]])
            elif p["pk"] in GT:
                gparams.append(GT[p["pk"]])
                cparams.append("u64" if GT[p["pk"]] in ("Obj", "Val") else GT[p["pk"]])
            else:
                ok = False
        if not ok:
            continue
        for recv in sorted(by_sig[sig]):
            fname = gname_of(mname, recv, tuple(gparams))
            groups.setdefault((fname, recv, tuple(gparams)), []).append((sig, cparams, ret))
    nobj = 0
    RET = {"bool": ("bool", "return qtc_ret_bool();"), "int": ("i64", "return qtc_ret_int();"),
           "uint": ("i64", "return qtc_ret_int();"), "double": ("f64", "return qtc_ret_double();"),
           "str": ("u8[>..]", "return view(qtc_ret_str());"), "bytes": ("u8[>..]", "return view(qtc_ret_str());"),
           "obj": ("Obj", "return Obj { h: qtc_ret_obj() };"), "value": ("Val", "return Val { h: qtc_ret_val() };"),
           "list": ("Val", "return Val { h: qtc_ret_val() };"), "map": ("Val", "return Val { h: qtc_ret_val() };"),
           "variant": ("Val", "return Val { h: qtc_ret_val() };")}
    for (fname, recv, gparams), sigs in groups.items():
        if len({s for s, _, _ in sigs}) != 1:
            continue   # several Qt signatures behind one Goose function: the Val form picks at run time
        sig, cparams, ret = sigs[0]
        ename = entries["inline_methods"][sig]
        externs[ename] = "    fn %s(%s) -> i32;" % (ename, ", ".join(["receiver: u64"] + ["a%d: %s" % (i, t) for i, t in enumerate(cparams)]))
        args = ["o.h"] + ["a%d.h" % i if t in ("Obj", "Val") else "a%d" % i for i, t in enumerate(gparams)]
        head = "fn %s(o: %s%s)" % (fname, recv, "".join(", a%d: %s" % (i, t) for i, t in enumerate(gparams)))
        r = RET.get(ret)
        if r:
            out.append("%s -> %s { %s(%s); %s }" % (head, r[0], ename, ", ".join(args), r[1]))
        else:
            out.append("%s { %s(%s); }" % (head, ename, ", ".join(args)))
        nobj += 1
    out[4:4] = ["// qtc_inline.h and the qtcmi_ entry points of qtc_direct.h", 'extern "qtc" {'] + \
        [externs[k] for k in sorted(externs)] + ["}", ""]
    with open(os.path.join(out_dir, "values.goose"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("values.goose: %d value functions, %d object methods taking value structs" % (nfun, nobj))
